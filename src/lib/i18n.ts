export const dictionaries: Record<SiteLocale, Dictionary> = {
  'zh-CN': zhCN,
  en,
  ja,
}

export function resolveLocale(value: string | null | undefined): SiteLocale {
  const normalized = value?.trim().toLowerCase()
  if (normalized === 'zh-cn' || normalized?.startsWith('zh-')) return 'zh-CN'
  if (normalized === 'en' || normalized?.startsWith('en-')) return 'en'
  if (normalized === 'ja' || normalized?.startsWith('ja-')) return 'ja'
  return DEFAULT_LOCALE
}

export function formatMessage(
  template: string,
  params: Record<string, string | number> = {},
): string {
  return template.replace(/\{([a-zA-Z][\w-]*)\}/g, (match, key: string) => (
    Object.hasOwn(params, key) ? String(params[key]) : match
  ))
}

export function getTranslation(
  locale: SiteLocale,
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  return formatMessage(dictionaries[locale][key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key, params)
}
